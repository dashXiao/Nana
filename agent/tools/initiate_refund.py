"""initiate_refund: request a refund for an order.

Design:
- The agent session injects user_id; the LLM selects order_id from query_orders results.
- Ownership mismatch returns UNAUTHORIZED independently of any prompt instructions.
- Refunding an already refunded order returns INVALID_STATE, preventing duplicate updates.
- The tool does not enforce the return window. The model evaluates this business policy
  using days_since_shipped and knowledge/policies.md, guided by the system prompt.
  The tool enforces only existence, ownership, and state.
"""

from __future__ import annotations

from pydantic import BaseModel, Field

from db import db_session

from ._contract import ErrorCode, ToolSpec, err, ok


class InitiateRefundInput(BaseModel):
    user_id: str = Field(
        description="Current session user ID, injected by the agent from session context; never generated by the LLM."
    )
    order_id: str = Field(
        description="Order ID to refund, such as O005, selected from query_orders results."
    )


def initiate_refund_handler(args: InitiateRefundInput) -> dict:
    """Validate existence, ownership, then refund state; this order defines error precedence."""
    with db_session() as conn:
        row = conn.execute(
            "SELECT user_id, status FROM orders WHERE order_id = ?",
            (args.order_id,),
        ).fetchone()

        if row is None:
            return err(ErrorCode.NOT_FOUND, f"Order {args.order_id} does not exist")

        if row["user_id"] != args.user_id:
            return err(
                ErrorCode.UNAUTHORIZED,
                f"Order {args.order_id} does not belong to the current user",
            )

        if row["status"] == "refunded":
            return err(
                ErrorCode.INVALID_STATE,
                f"Order {args.order_id} has already been refunded; repeat refunds are not allowed",
            )

        conn.execute(
            "UPDATE orders SET status = 'refunded' WHERE order_id = ?",
            (args.order_id,),
        )

    return ok({"order_id": args.order_id, "status": "refunded"})


INITIATE_REFUND_SPEC = ToolSpec(
    name="initiate_refund",
    description=(
        "Initiate a refund for the specified order and set its status to refunded. "
        "The tool checks existence, ownership, and state: NOT_FOUND, UNAUTHORIZED, and INVALID_STATE."
    ),
    input_model=InitiateRefundInput,
    handler=initiate_refund_handler,
)
