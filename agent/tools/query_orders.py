"""query_orders: retrieve all orders for the current user, newest first.

Design:
- Accept only user_id, not order_id, to avoid cross-user order enumeration.
- The agent injects user_id from session context rather than trusting the LLM or user input.
- Retrieve the full list before resolving references, since users often do not know order IDs.
"""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field

from db import db_session

from ._contract import ErrorCode, ToolSpec, err, ok


class QueryOrdersInput(BaseModel):
    user_id: str = Field(
        description="Current session user ID, such as U001, injected by the agent; never generated by the LLM."
    )


def _days_since(dt_str: str | None, now: datetime) -> int | None:
    """Whole days since an ISO timestamp; None returns None."""
    if not dt_str:
        return None
    dt = datetime.fromisoformat(dt_str)
    return max(0, (now - dt).days)


def query_orders_handler(args: QueryOrdersInput) -> dict:
    """Validate the user, retrieve orders, and compute days_since_shipped."""
    with db_session() as conn:
        user = conn.execute(
            "SELECT 1 FROM users WHERE user_id = ?", (args.user_id,)
        ).fetchone()
        if user is None:
            return err(ErrorCode.NOT_FOUND, f"User {args.user_id} does not exist")

        rows = conn.execute(
            """
            SELECT o.order_id, o.product_id, p.name AS product_name,
                   o.status, o.created_at, o.shipped_at
            FROM orders o
            JOIN products p ON p.product_id = o.product_id
            WHERE o.user_id = ?
            ORDER BY o.created_at DESC
            """,
            (args.user_id,),
        ).fetchall()

    now = datetime.now()
    orders = [
        {
            "order_id": r["order_id"],
            "product_id": r["product_id"],
            "product_name": r["product_name"],
            "status": r["status"],
            "created_at": r["created_at"],
            "shipped_at": r["shipped_at"],
            "days_since_shipped": _days_since(r["shipped_at"], now),
        }
        for r in rows
    ]
    return ok({"orders": orders, "count": len(orders)})


QUERY_ORDERS_SPEC = ToolSpec(
    name="query_orders",
    description=(
        "Retrieve all orders for the current user, newest first. "
        "Each includes its ID, product, status, order/shipping timestamps, and days since shipping."
    ),
    input_model=QueryOrdersInput,
    handler=query_orders_handler,
)
