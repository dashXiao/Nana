"""Shared tool contract: OpenAI function schemas and a uniform result format.

Conventions:
- ToolSpec declares each tool: name, description, Pydantic input model, and handler.
- Pydantic validates arguments and generates the JSON Schema exposed to the LLM.
- Results use one of these shapes:
    Success → {"ok": True, "data": <any>}
    Failure → {"ok": False, "error_code": <str>, "message": <str>}
  JSON serialization lets the LLM distinguish an empty successful result from a failed call.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Callable

from pydantic import BaseModel, ValidationError


class ErrorCode:
    """Stable tool-layer error codes; reuse existing codes where possible."""

    INVALID_INPUT = "INVALID_INPUT"    # Invalid arguments or missing fields
    NOT_FOUND = "NOT_FOUND"            # Resource not found, such as an order or product
    UNAUTHORIZED = "UNAUTHORIZED"      # Unauthorized access to another user's data
    INVALID_STATE = "INVALID_STATE"    # Operation disallowed by resource state, such as a repeat refund
    INTERNAL = "INTERNAL"              # Unexpected handler exception


def ok(data: Any) -> dict:
    """Wrap a successful result."""
    return {"ok": True, "data": data}


def err(code: str, message: str) -> dict:
    """Wrap a failed result."""
    return {"ok": False, "error_code": code, "message": message}


@dataclass
class ToolSpec:
    """Contract for a single tool."""

    name: str
    description: str
    input_model: type[BaseModel]
    handler: Callable[[BaseModel], dict]

    def to_openai(self) -> dict:
        """Convert to an entry in the OpenAI chat.completions tools array."""
        schema = self.input_model.model_json_schema()
        # Remove the title generated by Pydantic; it is not needed in the tool schema.
        schema.pop("title", None)
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": schema,
            },
        }

    def invoke(self, arguments: str | dict) -> dict:
        """Validate LLM arguments (JSON string or dict), then invoke the handler.

        Validation and handler errors are returned as err(...) results.
        """
        try:
            if isinstance(arguments, str):
                arguments = json.loads(arguments) if arguments else {}
        except json.JSONDecodeError as e:
            return err(ErrorCode.INVALID_INPUT, f"arguments is not valid JSON: {e}")

        try:
            args = self.input_model(**arguments)
        except ValidationError as e:
            first = e.errors()[0] if e.errors() else {}
            field = ".".join(str(x) for x in first.get("loc", [])) or "<root>"
            msg = first.get("msg", str(e))
            return err(ErrorCode.INVALID_INPUT, f"{field}: {msg}")

        try:
            return self.handler(args)
        except Exception as exc:  # noqa: BLE001 — Boundary error handling
            return err(ErrorCode.INTERNAL, f"{type(exc).__name__}: {exc}")


class ToolRegistry:
    """Look up ToolSpec by name for dispatch from the agent loop."""

    def __init__(self, specs: list[ToolSpec]):
        self._by_name: dict[str, ToolSpec] = {s.name: s for s in specs}
        if len(self._by_name) != len(specs):
            raise ValueError("Duplicate tool names; name must be unique")

    def get(self, name: str) -> ToolSpec | None:
        return self._by_name.get(name)

    def openai_tools(self) -> list[dict]:
        return [s.to_openai() for s in self._by_name.values()]

    def dispatch(self, name: str, arguments: str | dict) -> dict:
        """Dispatch a tool by name, returning NOT_FOUND if it is not registered."""
        spec = self.get(name)
        if spec is None:
            return err(ErrorCode.NOT_FOUND, f"Unknown tool: {name}")
        return spec.invoke(arguments)
